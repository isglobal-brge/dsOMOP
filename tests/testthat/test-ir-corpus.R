# WS-2 corpus checks (design-2.10.3 sections 5 and 12.2).
#
# fixtures/ir-v1-corpus.json holds every distinct plan the pinned 2.10.2
# server and client suites build or execute (captured with tools/ws2/), with
# provenance (package, file, test). Two kinds of evidence, kept apart:
#
#   1. the binding of each corpus plan to its frozen class
#      (fixtures/v1-corpus-classes.csv, WS-0, keyed package:file:<test>): the
#      outcome of the frozen validation sequence must agree with the reviewed
#      class of the block that built the plan;
#   2. golden snapshots (fixtures/ir-v1-golden.json, tools/ws2/make_ir_golden.R)
#      of the normalised IR documents, digests and annexes: a regression
#      check of the lowering, generated by the implementation itself, so it
#      is NOT result-equivalence evidence. Result fidelity against independent
#      baseline results is test-ir-results.R (tools/ws2/capture_results.R).

.irc_fixture <- function(name) {
  jsonlite::fromJSON(testthat::test_path("fixtures", name), simplifyVector = FALSE)
}

.irc_outcome <- function(plan) {
  tryCatch({
    # captured execution plans may carry server-injected frames: validate the
    # wire part, as .planExecute() does
    wire <- .planWirePart(plan)
    ir <- .irPrepare(wire$plan, handle = NULL, scope_tables = wire$scope_tables)
    if (is.null(ir)) list(outcome = "no_ir") else list(outcome = "ir", ir = ir)
  }, dsomop_plan_rejection = function(e) list(outcome = "refused", message = conditionMessage(e)))
}

# The class rows of the blocks a corpus plan came from. The archetype battery
# of the client's test-recipe-declarative.R names its tests dynamically
# ("declarative archetype: <name>"), which the static WS-0 inventory keys as
# the one battery block.
.irc_classes <- function(rec, rows) {
  keys <- vapply(rec$sources, function(s) {
    test <- s$test
    if (identical(s$file, "test-recipe-declarative.R") && grepl("^declarative archetype: ", test)) {
      test <- "declarative archetype battery covers >= 40 archetypes"
    }
    paste(s$package, s$file, test, sep = "\r")
  }, "")
  rows$class[paste(rows$package, rows$file, rows$test, sep = "\r") %in% keys]
}

test_that("every corpus plan belongs to a reviewed block of the frozen classification", {
  corpus <- .irc_fixture("ir-v1-corpus.json")
  rows <- utils::read.csv(testthat::test_path("fixtures", "v1-corpus-classes.csv"),
                          stringsAsFactors = FALSE)
  expect_gte(length(corpus), 400L)
  unbound <- vapply(corpus, function(r) length(.irc_classes(r, rows)) == 0L, logical(1))
  expect_identical(vapply(corpus[unbound], `[[`, "", "id"), character(0))
})

# Plans of blocks classed safe that only check client-side serialisation (a
# JSON round trip, a DSL builder) and are invalid for any server; no baseline
# suite executed or validated them (executed = NA in the corpus).
.IRC_CLIENT_ONLY_INVALID <- c(
  "v1-129", "v1-301", "v1-302", # filters$custom {op: and, children: [...]}: no such filter field
  "v1-352"                      # a dictionary over outputs the plan does not declare
)

# A-27/CR-28 newly refuses these four frozen translation/factor conflicts.
# Keep the historical class rows and IR snapshots unchanged.
.IRC_A27_CONFLICTS <- c("v1-125", "v1-126", "v1-244", "v1-246")
.irc_expect_a27_conflict <- function(rec, got) {
  expect_identical(rec$plan$options$translate_concepts, TRUE, info = rec$id)
  expect_identical(rec$plan$options$factor_concepts, FALSE, info = rec$id)
  expect_identical(got$outcome, "refused", info = rec$id)
  expect_match(got$message, "factor_concepts = FALSE conflicts with concept translation", fixed = TRUE)
}

test_that("validation outcomes agree with each block's class and the baseline's run", {
  corpus <- .irc_fixture("ir-v1-corpus.json")
  rows <- utils::read.csv(testthat::test_path("fixtures", "v1-corpus-classes.csv"),
                          stringsAsFactors = FALSE)
  accepted <- c("ir", "no_ir")
  refused_ids <- character(0)
  for (rec in corpus) {
    classes <- unique(.irc_classes(rec, rows))
    got <- .irc_outcome(rec$plan)
    info <- paste(rec$id, paste(classes, collapse = ","), got$message %||% "")
    if (rec$id %in% .IRC_A27_CONFLICTS) {
      .irc_expect_a27_conflict(rec, got)
      next
    }
    # every plan the baseline executor ran is accepted: its result is the
    # unchanged v1 executor's (test-ir-results.R compares those results)
    if (isTRUE(rec$executed)) expect_true(got$outcome %in% accepted, info = info)
    # a newly permitted shape the baseline refused is accepted now
    if (isFALSE(rec$executed) && length(classes) && all(classes == "newly_permitted")) {
      expect_true(got$outcome %in% accepted, info = info)
    }
    # a refusal is either an invalid plan of an unchanged_invalid block or one
    # of the documented never-executed client fixtures
    if (identical(got$outcome, "refused")) {
      refused_ids <- c(refused_ids, rec$id)
      expect_true("unchanged_invalid" %in% classes ||
                    (is.null(rec$executed) && rec$id %in% .IRC_CLIENT_ONLY_INVALID), info = info)
    }
  }
  expect_true(all(.IRC_CLIENT_ONLY_INVALID %in% refused_ids))
})

test_that("every corpus plan reproduces its golden IR document, digest and annex", {
  corpus <- .irc_fixture("ir-v1-corpus.json")
  golden <- .irc_fixture("ir-v1-golden.json")
  expect_identical(vapply(corpus, `[[`, "", "id"), vapply(golden, `[[`, "", "id"))
  for (i in seq_along(corpus)) {
    rec <- corpus[[i]]
    want <- golden[[i]]
    got <- .irc_outcome(rec$plan)
    if (rec$id %in% .IRC_A27_CONFLICTS) {
      expect_identical(want$outcome, "ir", info = rec$id)
      expect_identical(.planSemanticDigest(want$ir)$sha256, want$digest, info = rec$id)
      .irc_expect_a27_conflict(rec, got)
      next
    }
    expect_identical(got$outcome, want$outcome, info = rec$id)
    if (identical(want$outcome, "ir") && identical(got$outcome, "ir")) {
      doc <- .irDocument(got$ir)
      # The frozen pre-A27 document and digest stay intact as the baseline.
      # A-27 adds exactly two empty maps to options and each variable; spell
      # out that amendment independently instead of re-normalizing with the
      # implementation being tested or regenerating the historical fixture.
      expect_identical(.planSemanticDigest(want$ir)$sha256, want$digest, info = rec$id)
      amended <- want$ir
      empty <- stats::setNames(list(), character())
      amended$options$labels <- empty
      amended$options$column_names <- empty
      for (name in names(amended$variables)) {
        amended$variables[[name]]$labels <- empty
        amended$variables[[name]]$column_names <- empty
      }
      expect_identical(.jcsCanonical(doc), .jcsCanonical(amended), info = rec$id)
      expect_identical(.planSemanticDigest(doc)$sha256,
                       .planSemanticDigest(amended)$sha256, info = rec$id)
      annex <- attr(got$ir, "legacy_annex")
      expect_identical(if (is.null(annex)) "null" else .jcsCanonical(annex),
                       if (is.null(want$annex)) "null" else .jcsCanonical(want$annex), info = rec$id)
      expect_true(.jsonSchemaValidate(.irSchema("ir-v2"), want$ir)$valid, info = rec$id)
      # the IR document carries no server-private residue any more (A-10)
      expect_null(attr(got$ir, "legacy_residue"), info = rec$id)
    }
    if (identical(want$outcome, "refused")) {
      expect_identical(got$message, want$message, info = rec$id)
    }
  }
})
