S <- function(...) .numberEffective(list(...))
Tn <- function(method,...) list(kind="transform",method=method,...)
Rn <- function(method,...) list(kind="round",method=method,...)
P <- function(...) list(pipeline=list(...))
test_that("N01 N08 N19 N24 identity, directed rounds and presence retain types", {
  x<-c(-2,0,5.25,NA_real_)
  expect_identical(.numberPresent(x,S()),x)
  for(m in c("floor","ceiling","trunc","none")) expect_equal(.numberPresent(-1.75,P(Rn(m))),switch(m,floor=-2,ceiling=-1,trunc=-1,none=-1.75))
  expect_identical(.numberPresent(c(0,5,NA),S(representation="present")),c(1L,1L,0L))
  expect_identical(.numberPresent(c(0,5,NA),S(representation="missing")),c(0L,0L,1L))
  expect_identical(.numberPresent(NA_real_,S(representation="missing"),available=FALSE),NA_integer_)
})
test_that("N06 N07 N49 nearest decimal rounds actual binary64 values", {
  expect_equal(.numberPresent(c(1.25,1.75,-1.25),P(Rn("decimals",digits=1))),c(1.2,1.8,-1.2))
  expect_equal(.numberPresent(c(125,135),P(Rn("decimals",digits=-1))),c(120,140))
  expect_equal(.numberPresent(c(125,135,.0125,0),P(Rn("significant",digits=2))),c(120,140,.013,0))
  expect_equal(.numberPresent(c(1.25-2^-52,1.25,1.25+2^-52),P(Rn("decimals",digits=1))),c(1.2,1.2,1.3))
  x<-bit64::as.integer64("9007199254740993")
  expect_identical(.numberPresent(x,P(Tn("identity"),Rn("none"))),x)
  expect_error(.numberPresent(x,P(Rn("decimals",digits=0))),"retain raw/count")
})
test_that("N09 N10 N11 N12 declared bins preserve full ordered domains", {
  x<-.numberPresent(c(-1,0,5,10,NA),S(representation="bins",breaks=c(-Inf,0,5,10,Inf)))
  expect_true(is.ordered(x));expect_identical(as.character(x),c("(-Inf,0)","[0,5)","[5,10)","[10,Inf)",NA))
  expect_length(levels(x),4)
  expect_identical(as.character(.numberPresent(c(0,5,10,11),S(representation="bins",breaks=c(0,5,10),closed="right"))),c(NA,"(0,5]","(5,10]",NA))
  expect_identical(as.character(.numberPresent(c(3,100),S(representation="bins",grid="count_1_2_5"))),c("[2,5)","[100,Inf)"))
  for(g in names(.NUMBER_GRIDS))expect_equal(unlist(S(representation="bins",grid=g)$pipeline[[1]]$breaks),.NUMBER_GRIDS[[g]])
  expect_identical(levels(.numberPresent(1,S(representation="bins",breaks=c(0,5,10),labels=c("Zulu","Alpha")))),c("Zulu","Alpha"))
  expect_error(S(representation="bins",breaks=c(0,5,10),labels=c("a","a")),"labels")
})
test_that("N13 N14 N15 N16 reference/threshold categories and every flag", {
  expect_identical(as.character(.numberPresent(c(4,5,10,11),S(representation="category"),ranges=list(low=rep(5,4),high=rep(10,4)))),c("low","normal","normal","high"))
  expect_identical(as.character(.numberPresent(c(4,5,10,11),S(representation="category",thresholds=c(5,10)))),c("low","normal","normal","high"))
  expect_true(all(is.na(.numberPresent(c(4,5),S(representation="category"),ranges=list(low=c(NA,10),high=c(10,5))))))
  for(op in c("lt","le","gt","ge","eq","ne"))expect_identical(.numberPresent(c(4,5,6,NA),S(representation="flag",op=op,thresholds=5)),as.integer(switch(op,lt=c(T,F,F,NA),le=c(T,T,F,NA),gt=c(F,F,T,NA),ge=c(F,T,T,NA),eq=c(F,T,F,NA),ne=c(T,F,T,NA))))
  for(closed in c("left","right"))for(op in c("inside","outside")) {
    want<-if(closed=="left")c(1L,0L,NA_integer_) else c(0L,1L,NA_integer_)
    if(op=="outside")want<-1L-want
    expect_identical(.numberPresent(c(5,10,NA),S(representation="flag",op=op,thresholds=c(5,10),closed=closed)),want)
  }
})
test_that("N17 N18 N19 N20 N21 N38 transform domains are private typed missing", {
  for(m in c("log","log10","log2"))expect_equal(.numberPresent(c(0,-1,NA),P(Tn(m))),rep(NA_real_,3))
  expect_equal(.numberPresent(exp(1),P(Tn("log"))),1)
  expect_equal(.numberPresent(100,P(Tn("log10"))),2)
  expect_equal(.numberPresent(8,P(Tn("log2"))),3)
  expect_equal(.numberPresent(c(0,-1),P(Tn("log1p"))),c(0,NA))
  expect_equal(.numberPresent(c(9,-1),P(Tn("sqrt"))),c(3,NA))
  expect_equal(.numberPresent(-3,P(Tn("abs"))),3)
  expect_equal(.numberPresent(c(0,1000),P(Tn("exp"))),c(1,NA))
  expect_equal(.numberPresent(0,P(Tn("expm1"))),0)
  expect_equal(.numberPresent(.125,P(Tn("affine",factor=100,offset=0))),12.5)
  expect_equal(.numberPresent(14,P(Tn("standardize",center=10,scale=2))),2)
  expect_equal(.numberPresent(c(-1,9,16),P(Tn("clip",lower=0,upper=10),Tn("sqrt"))),c(0,3,sqrt(10)))
  expect_equal(.numberPresent(c(NaN,Inf,-Inf),S()),rep(NA_real_,3))
  expect_error(S(transform=list(method="standardize",center=0,scale=0)),"positive")
})
test_that("N04 N05 N50 N51 N53 units and ordered stages compose once", {
  expect_equal(.numberPresent(14,S(unit=list(kind="fixed_unit",from="days",to="weeks",factor=1/7)),unit="days"),2)
  expect_error(.numberPresent(14,S(unit=list(kind="fixed_unit",from="days",to="weeks",factor=1/7)),unit="count"),"matching")
  u<-list(kind="fixed_unit",from="unit:9002",to="unit:9001",factor=2,offset=0)
  b<-list(kind="bins",breaks=c(-Inf,5,10,Inf));c<-list(kind="category",range="bins",category_map=c("low","normal","high"))
  expect_identical(as.character(.numberPresent(4.98,P(u,Rn("decimals",digits=1),b,c),unit="unit:9002")),"high")
  expect_identical(as.character(.numberPresent(4.98,P(u,b,c),unit="unit:9002")),"normal")
  expect_error(.numberEffective(P(b,Rn("floor"))),"Arithmetic")
  expect_error(.numberEffective(P(b,list(kind="category",range="bins",category_map=c("high","normal","low")))),"nondecreasing")
  expect_equal(.numberEffective(list(rounding=list(method="none")),list(rounding=list(method="floor")))$pipeline[[1]]$method,"none")
})

test_that("N38 N49 precision bounds and count widths are lossless", {
  for(d in c(-309,309))expect_error(.numberRoundCheck(list(method="decimals",digits=d)),"digits")
  for(d in c(0,18))expect_error(.numberRoundCheck(list(method="significant",digits=d)),"digits")
  expect_identical(as.character(.reduceCoerce(list(2147483648),"integer")),"2147483648")
  expect_s3_class(.reduceCoerce(list(2147483648),"integer"),"integer64")
  expect_equal(.numberRoundOne(2^-1074,"significant",1),2^-1074)
  expect_equal(.numberRoundOne(.Machine$double.xmax,"significant",17),.Machine$double.xmax)
})

