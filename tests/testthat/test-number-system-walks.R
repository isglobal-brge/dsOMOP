test_that("N56 N69 N70 N72 closed masks preserve UNKNOWN and reference pairing", {
  # Same explicit complete-pair/nonnegative mask in numerator and denominator.
  mask<-list(and=list(.nt("x","not_null",NULL),.nt("w","not_null",NULL),.nt("w",">=",0)))
  # Unary predicates have no value member in mutate-v1.
  mask$and[[1]]$value<-NULL;mask$and[[2]]$value<-NULL
  x<-c(2,8,NA,4);w<-c(1,3,100,0)
  numerator<-.ne(.nif(mask,.no("*",.nc("x"),.nc("w")),.nl(0)),x=x,w=w)
  denominator<-.ne(.nif(mask,.nc("w"),.nl(0)),x=x,w=w)
  expect_equal(sum(numerator)/sum(denominator),6.5)
  expect_equal(.ne(.no("/",.nc("missing"),.nc("total")),missing=c(1,0),total=c(3,0)),c(1/3,NA))
  odds<-.nif(list(and=list(.nt("x",">",0),.nt("x","<",1))),.no("/",.nc("x"),.no("-",.nl(1),.nc("x"))))
  s<-list(pipeline=list(list(kind="expression",exprs=.nr(odds),unit="coordinate:odds"),list(kind="transform",method="log")))
  expect_equal(.numberPresent(c(.25,.5,0,1,-1,2,NA),s),c(log(1/3),0,rep(NA_real_,5)))
  ratio<-.nif(.nt("h",">",0),.no("/",.nc("x"),.nc("h")))
  expect_equal(.ne(ratio,x=c(20,30,20,20),h=c(10,15,0,NA)),c(2,2,NA,NA))
  expect_equal(.ne(ratio,x=2*c(20,30)+10,h=2*c(10,15)+10),c(50/30,70/40))
  req<-list(version=1L,assign=list(list(name="early",expr=.no("+",.nc("x"),.nl(1))),list(name="later",expr=list(case_when=list(cases=list(list(when=.nt("early",">",2),then=.nl(10)),list(when=.nt("x",">",0),then=.nl(20))),`else`=.nl(0))))))
  expect_equal(.numberExpression(req,data.frame(x=c(2,1,NA))),c(10,20,NA))
  bad<-list("system('id')",~x+1,list(call="system",args=list("id")),list(op="^",args=list(.nc("x"),.nl(2))),list(col="person_id"),list(col="unknown"),list(col="x",extra=1))
  for(expr in bad)expect_error(.numberExpression(.nr(expr),data.frame(x=1)),class="omop_number_error")
})
