# Hand-checkable A-29 worked workflows through the shared closed evaluator.
.nc <- function(x)list(col=x)
.nl <- function(x)list(lit=x)
.no <- function(op,...)list(op=op,args=list(...))
.nr <- function(expr,name="answer")list(version=1L,assign=list(list(name=name,expr=expr)))
.ne <- function(expr,...) .numberExpression(.nr(expr),data.frame(...))
.nt <- function(v,op,value)list(var=v,op=op,value=value)
.nif <- function(test,yes,no=list(lit=NULL,as="numeric"))list(ifelse=list(test=test,yes=yes,no=no))

test_that("N30 N31 N32 N33 N34 N35 longitudinal methods use observed endpoints and origins", {
  rows<-function(v,days=c(0,2,4))data.frame(start_date=as.Date("2020-01-01")+days,v=v)
  change<-function(r,m,missing="skip",...) .numberChangeValues(r,c(list(kind="number_change",source=list(event="e"),value="value",method=m,missing=missing),list(...)))
  r<-rows(c(2,NA,8))
  expect_equal(change(r,"difference"),6);expect_equal(change(r,"percent_change"),300)
  expect_equal(change(r,"ratio"),4);expect_true(is.na(change(rows(c(0,NA,8)),"ratio")))
  expect_equal(change(rows(c(-2,NA,-1)),"percent_change"),-50)
  expect_true(is.na(change(rows(c(NA,2,NA)),"difference")))
  expect_true(is.na(change(rows(c(2,8,NA)),"difference",missing="keep")))
  expect_equal(change(rows(c(2,6,10)),"slope",time_unit="weeks"),14)
  expect_true(is.na(change(rows(c(2,6,10),c(0,0,0)),"slope")))
  expect_equal(change(rows(c(2,4,8)),"time_to_threshold",threshold=5,op="ge"),4)
  expect_equal(change(rows(c(8,4,8)),"time_to_threshold",threshold=5),0)
  expect_true(is.na(change(rows(c(2,4,3)),"time_to_threshold",threshold=5)))
  d<-list(kind="number_change",source=list(event="e"),value="value",method="time_to_threshold",missing="skip",threshold=5,reference=list(kind="index"),time_unit="weeks")
  expect_equal(.numberChangeValues(rows(c(8,4,8),c(-14,0,14)),d,as.Date("2020-01-01")),2)
  expect_true(is.na(.numberChangeValues(rows(c(8,4,8)),d,as.Date(NA))))
})
test_that("N22 N25 N26 N29 existing selector, count and predicate oracles remain explicit", {
  x<-list(start_date=as.Date("2020-01-01")+c(0,0,2),v=c(2,NA,8),visit_id=c("a","a",NA),concept_id=c(1,2,2))
  for(k in c("row","day","visit","concept"))expect_equal(.reduceOne("count",x,list(distinct=k)),switch(k,row=3L,day=2L,visit=1L,concept=2L))
  expect_equal(.reduceOne("n_distinct",x,list()),2L);expect_equal(.reduceOne("binary",x,list()),1L)
  expect_equal(.reduceOne("first_value",x,list()),2);expect_equal(.reduceOne("last_value",x,list()),8)
  expect_equal(.reduceOne("nth_value",x,list(n=2)),8);expect_true(is.na(.reduceOne("nth_value",x,list(n=2,missing="keep"))))
  x$start_date<-as.Date("2020-01-01")+c(0,2,4)
  expect_equal(.reduceOne("closest_value",x,list(),as.Date("2020-01-03")),2)
  expect_true(is.na(.reduceOne("closest_value",x,list(missing="keep"),as.Date("2020-01-03"))))
  x$v<-c(2,4,8)
  for(fn in c("mean","min","max","sum","median","sd","quantile","mode"))expect_equal(.reduceOne(fn,x,list(p=.25),value_type="numeric"),switch(fn,mean=14/3,min=2,max=8,sum=14,median=4,sd=sqrt(28/3),quantile=3,mode=2))
  x$v<-c(4,6,11);x$range_low<-rep(5,3);x$range_high<-rep(10,3)
  expect_equal(.reduceOne("abnormal_high",x,list()),1L);expect_equal(.reduceOne("abnormal_low",x,list()),1L)
  x$pred<-c(NA_integer_,0L,0L)
  expect_true(is.na(.reduceOne("any",x,list())));expect_equal(.reduceOne("all",x,list()),0L)
})
